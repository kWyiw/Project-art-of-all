# -*- coding: utf-8 -*-
import io

P = "规则书/大富翁层规则书.md"
s = io.open(P, encoding="utf-8").read()

def rep(old, new):
    global s
    n = s.count(old)
    if n != 1:
        print("COUNT", n, repr(old[:60]))
    s = s.replace(old, new, 1)

# 1. 地块表：删掉 Bonus / Drop 两行，Draw 去掉"珍宝版"限定
rep("| 奖励（碎片版）Bonus | — | `碎片 += min(等级,3) × 本次骰点` | |\n"
    "| 掉落 Drop | — | `碎片 -= 等级 × 本次骰点`（下限 0） | Bonus 有 min(等级,3) 上限，Drop **没有**（刻意的不对称） |\n"
    "| 奖励（珍宝版）Draw | — | 2 选 1 获得珍宝（免费） | 见 R-TILE-006 |",
    "| 奖励 Draw | — | 2 选 1 获得珍宝（免费） | 见 R-TILE-006 |")

# 2. 删掉 R-TILE-001 / R-TILE-002 两条只为 Bonus/Drop 服务的规则
rep("R-TILE-001  Bonus/Drop 的骰点：**复用本次移动骰**（不重投）。\n"
    "            判定：走到该格时用 R-MOVE-001 掷出的那个值。\n",
    "")
rep("R-TILE-002  Bonus 的等级上限为 3；Drop 无上限。\n", "")

# 3. 经济：碎片来源去掉 Bonus 格
rep("R-ECO-002  碎片获得：Bonus 格、奖励格折现、销毁珍宝、战斗抢夺、全局发放。",
    "R-ECO-002  碎片获得：奖励格折现、销毁珍宝、战斗抢夺、全局发放。")

# 4. 碎片量级表：删掉 Bonus 增量 / Drop 减量两行
rep("| Bonus 格增量 | `min(等级,3) × 骰(1~6)` → 1~18 | 与阈值表 15~210 同量级 |\n"
    "| Drop 格减量 | `等级 × 骰` → 1~30 | 比 Bonus 更狠（碎片更\"值钱\"）；要软化可取 `等级 × 骰 × 0.5` 向下取整 |\n",
    "")

