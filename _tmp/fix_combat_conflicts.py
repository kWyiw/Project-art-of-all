rep('**BT-5.9　充能不是状态，是一次性即时效果。**\n它不占状态栏，不因"被清除状态"而失效。',
    '**BT-5.9　充能是即时效果，但溢出量会留在这张牌上。**\n'
    '充能本身不占状态栏、不因"被清除状态"而失效；唯一被保留下来的是 BT-3.6 的 `chargeCarry`——\n'
    '它属于这张牌的**冷却数据**，不是"状态"，因此不被"清除状态"类效果影响，只被"重置该牌冷却"类效果清掉。')

