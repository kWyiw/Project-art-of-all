import io, sys

P = '规则书/战斗规则书.md'
s = io.open(P, encoding='utf-8').read()
n = [0]

def rep(old, new):
    global s
    if old not in s:
        print('MISS', old[:40].encode('ascii', 'backslashreplace').decode())
        sys.exit(1)
    s = s.replace(old, new, 1)
    n[0] += 1

