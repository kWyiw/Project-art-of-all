rep('允许：战斗栏内重排、从背包把牌拖进战斗栏、把战斗栏的牌拖回背包、出售卡牌。受 CJ-5 宽度与 CJ-5.2 解锁等级约束。\n',
    '允许：战斗栏内重排、从背包把牌拖进战斗栏、把战斗栏的牌拖回背包、出售卡牌。受 CJ-5 宽度与 CJ-5.2 解锁等级约束。\n\n'
    '**BT-2.3.3　准备期内允许出售，但只限"改变牌组内容"的出售。**\n'
    '允许：出售卡牌（免费、不限次，CJ-6.5）。出售时效果照常结算（R-ECO-014），计入发起方本回合。\n'
    '不允许：购买、主动使用卡牌效果、打开商店。这三件事只在棋盘层做——否则 5 秒准备期会变成"临场刷牌"，\n'
    '把"调整阵容"变成"二次构筑"。\n')

# 2. BT-3.6：充能溢出存为 chargeCarry
rep('充能不会让 CD 变成负数，过量的充能会"存着"变成下次的提前量。',
    '充能不会让 CD 变成负数；超出当前剩余冷却的部分记为这张牌的 `chargeCarry`（tick），\n'
    '在该牌**下一次进入冷却**时从新 CD 里直接扣掉，扣到 0 为止、多出的部分丢弃。\n'
    '`chargeCarry` 不跨战斗：战斗结束即清零（与 BT-4.7 的"战斗内状态"同一生命周期）。')

